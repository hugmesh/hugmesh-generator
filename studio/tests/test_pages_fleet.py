def test_restart_routes_fleet_session_back_into_fleet_window(qapp, wiz, tmp_path):
    """RESTART on a fleet row opens the fleet window pinned to the SAME record:
    config reloaded, Review step, prior outcome archived into history on redispatch."""
    wiz.restart()
    cfg = FleetConfig(skip_x86=True, rpi_roles="pki desktop",
                      output_dir=str(tmp_path / "out"), jobs=5)
    s = bs.new_fleet_session(cfg, GENERATOR_DIR)
    bs.start(s)
    bs.update_image(s, 0, status="failed", exit_code=2)
    bs.finish(s, bs.FAILED, {"fleet": ["boom"]})
    os.makedirs(s.workdir, exist_ok=True)       # can_restart needs the workdir
    pb = _sessions_page(wiz).previous_builds
    pb.refresh()
    row = next(r for r in range(pb.table.rowCount())
               if pb.table.item(r, 0).text().startswith("fleet:"))
    pb.table.selectRow(row)
    pb._restart()                               # routes to the fleet window, no wizard box
    win = wiz.fleet_window
    assert win is not None and win.isVisible()
    page = win.page
    assert page.stack.currentIndex() == fleet_mod.STEP_REVIEW
    assert page.pending_session_id == s.id      # SAME record/workdir pinned
    assert page.collect() == cfg                # apply() is the exact inverse of collect()
    # redispatch reuses the record and archives the failed outcome
    page.driver.host = HOST
    page.driver.run = lambda cfg, backend, on_line=None: 0
    _dispatch_and_wait(qapp, page)
    (again,) = bs.load_all()
    assert again.id == s.id and again.status == "complete"
    assert again.restarts == 1
    assert again.history and again.history[-1]["status"] == "failed"


