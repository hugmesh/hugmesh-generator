# ── (f) MID-FLIGHT: interaction, single-instance, and closeEvent while a run is
# genuinely in progress (the worker PARKED on a threading.Event) ───────────────────────
@pytest.fixture
def held_run(qapp, wiz, tmp_path):
    """Dispatch a mocked run that PARKS mid-flight on an Event, so tests can
    interact with the UI while the run is genuinely in progress (the instant
    fake_run above never exercises that). Teardown always releases the worker
    and flushes finalization — a failed assertion never leaves a parked thread
    behind for the wiz fixture to tear down under."""
    ctx = {}

    def _launch(code=0):
        wiz.restart()
        win = fleet_mod.open_fleet_window(wiz)
        page = win.page
        page.driver.host = HOST
        hold, release = threading.Event(), threading.Event()

        def fake_run(cfg, backend, on_line=None):
            if on_line:
                on_line("mid-flight line")
            hold.set()                          # signal: genuinely in progress
            assert release.wait(30), "the test never released the held run"
            return code

        page.driver.run = fake_run
        page.output_dir.setText(str(tmp_path / "out"))
        page._goto(fleet_mod.STEP_REVIEW)
        assert page.problems.toPlainText() == "Preflight: OK"
        sid = page.pending_session_id
        page.next_btn.click()
        assert page.worker is not None and page.worker.isRunning()
        assert hold.wait(10), "the worker never reached mid-flight"
        ctx.update(win=win, page=page, sid=sid, release=release)
        return win, page, sid, release

    yield _launch
    if ctx:
        ctx["release"].set()
        page = ctx["page"]
        if page.worker is not None and page.worker.isRunning():
            page.worker.wait(5000)
        for _ in range(200):
            qapp.processEvents()
            if page._session is None:
                break
            time.sleep(0.01)


def _answer_close_box(monkeypatch, label):
    """Answer the NEXT QMessageBox headlessly (its exec() would otherwise spin a
    real modal loop offscreen): pick the button whose text contains ``label``,
    or the standard Cancel button when ``label`` is None."""
    def fake_exec(self):
        picked = None
        for b in self.buttons():
            if label is not None and label in b.text():
                picked = b
                break
        if picked is None:
            picked = self.button(QtWidgets.QMessageBox.StandardButton.Cancel)
        assert picked is not None, "the expected button is not on the box"
        self._picked = picked
        return 0

    monkeypatch.setattr(QtWidgets.QMessageBox, "exec", fake_exec)
    monkeypatch.setattr(QtWidgets.QMessageBox, "clickedButton",
                        lambda self: getattr(self, "_picked", None))


def test_sessions_widget_interactive_while_run_in_progress(qapp, wiz, held_run):
    """(4)(a) strictly: interact with Previous builds WHILE a fleet run is live —
    the old exec() modal (or any main-thread-blocking driver) would deadlock
    every line of this test body."""
    win, page, sid, release = held_run()
    welcome = _sessions_page(wiz)
    t0 = time.time()
    qapp.processEvents()                       # the event loop must stay live
    assert time.time() - t0 < 1.0, "event loop blocked while the run streams"
    pb = welcome.previous_builds
    pb.refresh()                               # refresh + filter mid-run
    qapp.processEvents()
    labels = [pb.table.item(r, 0).text() for r in range(pb.table.rowCount())]
    assert any(lb.startswith("fleet:") for lb in labels)
    pb.search.setText("fleet")
    qapp.processEvents()
    pb.search.setText("")
    qapp.processEvents()
    (rec,) = [s for s in bs.load_all() if s.id == sid]
    assert rec.status == bs.RUNNING            # honest mid-flight status
    assert not win.isModal()
    assert wiz.isEnabled() and welcome.isEnabled()
    release.set()
    _wait_finalized(qapp, page)
    (rec,) = [s for s in bs.load_all() if s.id == sid]
    assert rec.status == bs.COMPLETE


