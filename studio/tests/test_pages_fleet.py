def _drive(page, choices):
    """Set each choice on the page's REAL widgets, the way an operator would."""
    for name, val in choices.items():
        w = getattr(page, name)
        if isinstance(w, QtWidgets.QCheckBox):
            w.setChecked(bool(val))
        elif isinstance(w, QtWidgets.QComboBox):
            i = w.findData(val)
            assert i >= 0, f"{name}: {val!r} not in the combo"
            w.setCurrentIndex(i)
        elif isinstance(w, QtWidgets.QSpinBox):
            w.setValue(val)
        else:
            w.setText(val)


