    wiz.restart()
    win, page = _open_ready_window(wiz, tmp_path, code=0)
    sid_preview = None
    page._goto(fleet_mod.STEP_REVIEW)
    sid_preview = page.pending_session_id
    assert sid_preview                          # minted at Review (preview == dispatch)
