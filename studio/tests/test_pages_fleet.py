def _open_ready_window(wiz, tmp_path, code, lines=("fleet line 1", "fleet line 2")):
    """Open the wizard's fleet window with the driver mocked AT THE BOUNDARY
    (FleetDriver.run — no subprocess, no Qt main-thread blocking) and the pinned
    root host so native preflight is clean."""
    win = fleet_mod.open_fleet_window(wiz)
    page = win.page
    page.driver.host = HOST

    def fake_run(cfg, backend, on_line=None):
        if on_line:
            for ln in lines:
                on_line(ln)
        return code

    page.driver.run = fake_run
    page.output_dir.setText(str(tmp_path / "out"))
    return win, page


def _wait_finalized(qapp, page, timeout=10.0):
    """Pump the event loop until the worker exits AND the queued done signal has
    finalized the session record (page._session goes None)."""
    deadline = time.time() + timeout
    while page.worker.isRunning() and time.time() < deadline:
        qapp.processEvents()
        time.sleep(0.01)
    for _ in range(200):                       # flush the queued line/done signals
        qapp.processEvents()
        if page._session is None:
            break
        time.sleep(0.01)
    assert page._session is None, "the run never finalized its session record"


