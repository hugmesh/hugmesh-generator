"""The package resolution report for riscv64 and MIPS (hugmesh-generator#1056).

docs/catalog/package-resolution-report.json is the measured source of every greyed role
reason the catalog gives for riscv64 and MIPS (design: docs/design/PLATFORM-EXPANSION.md,
section 6). These tests hold three things:

1. the committed report covers every role on every measured arch, and every cell is a
   verdict (resolvable, or the first component missing and why);
2. the report is the script's output: its role list is the script's role list, and the
   committed Markdown is exactly what the script renders from the JSON;
3. a greyed catalog reason on a measured arch cites only components the report marks
   missing, so a reason cannot claim a gap nobody measured.

Pure-core: no Qt, no Docker, no Portage. Re-measuring needs the builder image; see the
script's docstring.
"""
from __future__ import annotations

import copy
import importlib.util
import json
import os

import pytest

STUDIO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.dirname(STUDIO_ROOT)
SCRIPT = os.path.join(GEN, "scripts", "package-resolution-report.py")


def _load_script():
    spec = importlib.util.spec_from_file_location("package_resolution_report", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def prr():
    assert os.path.isfile(SCRIPT), "scripts/package-resolution-report.py is missing"
    return _load_script()


@pytest.fixture(scope="module")
def report(prr):
    path = os.path.join(GEN, prr.REPORT_JSON)
    assert os.path.isfile(path), f"{prr.REPORT_JSON} is missing: run the script"
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


@pytest.fixture(scope="module")
def catalog(prr):
    with open(os.path.join(GEN, prr.DEVICE_CATALOG), encoding="utf-8") as fh:
        return json.load(fh)


# ── 1. coverage ───────────────────────────────────────────────────────────────────────


def test_report_is_dated_and_names_its_generator(prr, report):
    assert report["schema"] == prr.SCHEMA
    assert report["generator"] == prr.GENERATOR == "scripts/package-resolution-report.py"
    assert len(report["measured"]) == 10 and report["measured"][4] == "-"
    assert report["tree"]["timestamp"], "the Gentoo tree's timestamp is not recorded"
    assert report.get("image", {}).get("id", "").startswith("sha256:"), \
        "the builder image the report was measured in is not recorded"
    assert report["tree"]["categories"], "the tree's category list is not recorded"


def test_every_arch_the_issue_names_is_measured(report):
    catalog_arches = {a["catalog_arch"] for a in report["arches"]}
    assert catalog_arches == {"riscv64", "mips64el", "mips64"}
    by_id = {a["id"]: a for a in report["arches"]}
    # rv64/lp64d stacked with hardened + SELinux, exactly as the issue states
    rv = by_id["riscv64"]
    assert rv["profile"] == "default/linux/riscv/23.0/rv64/lp64d"
    assert rv["stack"] == ["features/hardened", "features/selinux"]
    # MIPS n64 in both byte orders
    assert by_id["mips64el"]["profile"] == "default/linux/mips/23.0/mipsel/n64"
    assert by_id["mips64"]["profile"] == "default/linux/mips/23.0/n64"
    for mips in ("mips64el", "mips64"):
        assert "features/selinux" in by_id[mips]["stack"]


def test_every_role_on_every_arch_has_a_verdict(prr, report):
    role_ids = [r["id"] for r in report["roles"]]
    assert role_ids == [t[0] for t in prr.TARGET_ROLES], \
        "the report's roles are not the script's TARGET_ROLES: re-run the script"
    for arch in report["arches"]:
        cells = report["cells"][arch["id"]]
        assert sorted(cells) == sorted(role_ids), f"{arch['id']} is missing roles"
        for rid, cell in cells.items():
            where = f"{arch['id']}/{rid}"
            assert cell["status"] in ("resolvable", "unresolvable"), where
            if cell["status"] == "resolvable":
                assert cell["first_missing"] is None, where
                assert cell["packages"] > 0, where
            else:
                fm = cell["first_missing"]
                assert fm and fm["atom"] and fm["reason"], \
                    f"{where} is unresolvable without a first missing component"
                assert not fm["reason"].startswith("unparsed"), \
                    f"{where}: emerge's failure was not understood: {fm['reason']}"


def test_role_sets_carry_no_board_plumbing(prr, report):
    for role in report["roles"]:
        stray = set(role["atoms"]) & set(prr.PLATFORM_PLUMBING)
        assert not stray, f"{role['id']} measures board plumbing {sorted(stray)}"
        assert role["atoms"], role["id"]


# ── 2. generated by the script ────────────────────────────────────────────────────────


def test_markdown_is_the_rendering_of_the_json(prr, report):
    with open(os.path.join(GEN, prr.REPORT_MD), encoding="utf-8") as fh:
        committed = fh.read()
    assert committed == prr.render_markdown(report), (
        f"{prr.REPORT_MD} is not the rendering of {prr.REPORT_JSON}: run "
        "scripts/package-resolution-report.py --render")


# ── 3. greyed reasons cite only measured gaps ─────────────────────────────────────────


def test_catalog_greyed_reasons_cite_only_missing_components(prr, report, catalog):
    bad = prr.catalog_citation_violations(catalog, report)
    assert not bad, "\n".join(bad)


def _measured_gap(prr, report, arch):
    gaps = sorted(prr.missing_components(report, arch))
    assert gaps, f"the report marks nothing missing on {arch}"
    return gaps[0]


def _present(prr, report, arch):
    """An atom the report measured on `arch` and did NOT mark missing."""
    gaps = prr.missing_components(report, arch)
    for role in report["roles"]:
        for atom in role["atoms"]:
            if atom not in gaps:
                return atom
    raise AssertionError(f"every measured atom is missing on {arch}")


def _greyed(dev_id, arch, reason, **extra):
    return {"id": dev_id, "arch": arch, "status": "unsupported", "reason": reason, **extra}


@pytest.mark.parametrize("arch", ["riscv64", "mips64el", "mips64"])
def test_checker_rejects_a_reason_citing_a_present_component(prr, report, catalog, arch):
    present = _present(prr, report, arch)
    cat = copy.deepcopy(catalog)
    cat["devices"].append(_greyed("probe", arch, f"needs {present}, which has no keyword"))
    bad = prr.catalog_citation_violations(cat, report)
    assert any(present in b and "probe" in b for b in bad), bad


@pytest.mark.parametrize("arch", ["riscv64", "mips64el", "mips64"])
def test_checker_accepts_a_reason_citing_a_measured_gap(prr, report, catalog, arch):
    gap = _measured_gap(prr, report, arch)
    cat = copy.deepcopy(catalog)
    cat["devices"].append(_greyed("probe", arch, f"{gap} has no {arch} keyword"))
    assert prr.catalog_citation_violations(cat, report) == []


def test_checker_reads_role_reason_maps_and_arch_labels(prr, report, catalog):
    present = _present(prr, report, "riscv64")
    gap = _measured_gap(prr, report, "riscv64")
    cat = copy.deepcopy(catalog)
    cat["devices"].append(_greyed("probe", "riscv64", "board reason",
                                  role_reasons={"pki": f"needs {present}",
                                                "backend": f"needs {gap}"}))
    bad = prr.catalog_citation_violations(cat, report)
    assert len(bad) == 1 and "role_reasons.pki" in bad[0] and present in bad[0], bad
    cat = copy.deepcopy(catalog)
    for a in cat["archs"]:
        if a["id"] == "riscv64":
            a["label"] = f"RISC-V 64 (no {present})"
    bad = prr.catalog_citation_violations(cat, report)
    assert len(bad) == 1 and "label" in bad[0], bad


def test_checker_scope_is_greyed_entries_on_measured_arches(prr, report, catalog):
    present = _present(prr, report, "riscv64")
    cat = copy.deepcopy(catalog)
    # a SUPPORTED row is not greyed, and arm64 is not a measured arch
    cat["devices"].append({"id": "ok", "arch": "riscv64", "status": "supported",
                           "reason": f"ships {present}"})
    cat["devices"].append(_greyed("arm", "arm64", f"needs {present}"))
    assert prr.catalog_citation_violations(cat, report) == []


def test_citation_parser_reads_versioned_and_prose_atoms(prr, report):
    cats = set(report["tree"]["categories"])
    text = ("no keyword for >=sec-policy/selinux-openrc-2.20170204-r4 or "
            "sys-cluster/kubelet[foo], and x86-64/arm64 or rv64/lp64d are not atoms")
    assert prr.cited_components(text, cats) == ["sec-policy/selinux-openrc",
                                                "sys-cluster/kubelet"]


def test_a_flag_conflict_is_not_counted_as_a_missing_component(prr):
    rep = {"arches": [{"id": "x", "catalog_arch": "x"}],
           "cells": {"x": {"r": {"first_missing": {
               "atom": ">=dev-libs/glib-2.82.0:2[introspection]",
               "reason": "no ebuild with the required USE flags"},
               "missing_atoms": [], "residual": None}}},
           "components": {"x": {}}}
    assert prr.missing_components(rep, "x") == set()
    rep["cells"]["x"]["r"]["first_missing"]["reason"] = "dev-libs/glib-2.82: masked by " \
                                                        "missing keyword"
    assert prr.missing_components(rep, "x") == {"dev-libs/glib"}


def test_failure_parser_names_the_wall_and_prefers_a_released_version(prr):
    text = "\n".join([
        '!!! All ebuilds that could satisfy "sec-policy/selinux-gpg" have been masked.',
        "!!! One of the following masked packages is required to complete your request:",
        "- sec-policy/selinux-gpg-9999::gentoo (masked by: missing keyword)",
        "- sec-policy/selinux-gpg-2.20260616_p1::gentoo (masked by: missing keyword)",
        '(dependency required by "app-crypt/gnupg-2.5.24::gentoo" [ebuild])',
    ])
    fm = prr.parse_failure(text)
    assert fm["atom"] == "sec-policy/selinux-gpg"
    assert fm["reason"] == "sec-policy/selinux-gpg-2.20260616_p1: masked by missing keyword"
    assert fm["required_by"] == ["app-crypt/gnupg-2.5.24::gentoo"]


def test_a_cycle_only_failure_counts_as_resolved(prr):
    out = prr.judge(1, "Total: 422 packages (422 new)\n * Error: circular dependencies:")
    assert out["resolved"] and out["packages"] == 422 and out["note"]
    masked = ('!!! All ebuilds that could satisfy "a-b/c" have been masked.\n'
              "Total: 5 packages\n * Error: circular dependencies:")
    assert not prr.judge(1, masked)["resolved"]
