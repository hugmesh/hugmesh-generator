#!/usr/bin/env python3
"""Write, or check, windows-build-requirements.txt: the hash-locked Python packages
the Windows installer is frozen from.

WHY A LOCK. The installer bundles whatever PySide6, PyInstaller, Pillow and tzdata
the build machine resolves that day, and people run what it produces. An unpinned
`pip install` makes that "whatever PyPI serves at build time". build-msi-wine.sh
installs this file with `pip install --require-hashes --only-binary=:all:`, so pip
refuses any file whose SHA-256 is not listed here.

The versions are a fact about a Windows CPython 3.12 install, not something to work
out on Linux: some dependencies carry markers (pywin32-ctypes is required only on
win32), and evaluating those on the build host would quietly drop them. So the input
is `pip freeze` run BY the Windows Python in the Wine prefix.

  # refresh: install the new top-level versions in a scratch prefix, then
  wine python -m pip freeze > freeze.txt
  python3 lock_windows_build.py freeze.txt > windows-build-requirements.txt

  # audit (network): every hash in the lock is one PyPI publishes for that exact release
  python3 lock_windows_build.py --check windows-build-requirements.txt

Only wheels this interpreter could install are listed (win_amd64 or pure-Python, for
CPython 3.12), so a lock line is something pip can actually pick. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request

PYTHON_TAG = "cp312"
HEADER = """\
# HASH-LOCKED build dependencies for the Windows installer (CPython 3.12, win_amd64).
# Generated by lock_windows_build.py from `pip freeze` run by the Windows Python in the
# Wine prefix; see that script for how to refresh or audit it. Installed with
#   pip install --require-hashes --only-binary=:all: -r windows-build-requirements.txt
"""
_WHEEL = re.compile(
    r"^(?P<name>.+?)-(?P<version>[^-]+)(-(?P<build>\d[^-]*))?-(?P<py>[^-]+)-(?P<abi>[^-]+)-(?P<plat>[^-]+)\.whl$")


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def parse_freeze(text: str) -> list[tuple[str, str]]:
    """``name==version`` lines. Anything else (a VCS pin, an editable) is refused: a
    lock cannot hash it."""
    out = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.fullmatch(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([A-Za-z0-9.!+_-]+)", line)
        if not m:
            raise SystemExit("not a `name==version` line, cannot lock it: %r" % line)
        if normalize(m.group(1)) == "pip":
            continue
        out.append((m.group(1), m.group(2)))
    return sorted(out, key=lambda p: normalize(p[0]))


def wheel_installs_here(filename: str) -> bool:
    """Could ``pip --only-binary=:all:`` pick this wheel on Windows CPython 3.12 x64?"""
    m = _WHEEL.match(filename)
    if not m:
        return False
    if m.group("plat") not in ("any", "win_amd64"):
        return False
    pys, abi = m.group("py").split("."), m.group("abi")
    if abi == "abi3":
        # cp310-abi3 runs on 3.10 and later; accept any cp3N abi3 wheel with N <= 12.
        return any(re.fullmatch(r"cp3(\d+)", p) and int(p[3:]) <= 12 for p in pys)
    if abi == "none":
        return all(p.startswith(("py", "cp3")) for p in pys) and any(
            p.startswith("py") or p == PYTHON_TAG for p in pys)
    return abi == PYTHON_TAG and PYTHON_TAG in pys


def pypi_release_files(name: str, version: str) -> list[dict]:
    url = "https://pypi.org/pypi/%s/%s/json" % (name, version)
    with urllib.request.urlopen(url, timeout=60) as resp:
        return json.load(resp)["urls"]


def hashes_for(name: str, version: str) -> list[str]:
    files = [f for f in pypi_release_files(name, version)
             if f["packagetype"] == "bdist_wheel" and wheel_installs_here(f["filename"])]
    if not files:
        raise SystemExit("%s==%s publishes no wheel installable on Windows CPython 3.12 x64, "
                         "and the build installs with --only-binary" % (name, version))
    return sorted(f["digests"]["sha256"] for f in files)


def render(pins: list[tuple[str, str]]) -> str:
    out = [HEADER]
    for name, version in pins:
        out.append("%s==%s \\\n%s\n" % (
            normalize(name), version,
            " \\\n".join("    --hash=sha256:%s" % h for h in hashes_for(name, version))))
    return "\n".join(out)


def parse_lock(text: str) -> list[tuple[str, str, list[str]]]:
    """``[(name, version, [sha256, ...]), ...]`` out of a pip requirements file with
    hashes."""
    joined = re.sub(r"\\\n\s*", " ", text)
    out = []
    for line in joined.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)\s+(.*)$", line)
        if not m:
            raise SystemExit("unparseable lock line: %r" % line[:80])
        out.append((m.group(1), m.group(2), re.findall(r"--hash=sha256:([0-9a-f]{64})", m.group(3))))
    return out


def check(lock_path: str) -> int:
    bad = 0
    with open(lock_path, encoding="utf-8") as fh:
        entries = parse_lock(fh.read())
    for name, version, hashes in entries:
        published = {f["digests"]["sha256"] for f in pypi_release_files(name, version)}
        unknown = [h for h in hashes if h not in published]
        status = "ok" if hashes and not unknown else "BAD"
        if status == "BAD":
            bad += 1
        print("%-4s %s==%s  %d hash(es)%s" % (
            status, name, version, len(hashes),
            "" if not unknown else "  NOT published on PyPI: " + ", ".join(h[:12] for h in unknown)))
    print("%d package(s) checked, %d bad" % (len(entries), bad))
    return 1 if bad else 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("input", help="a `pip freeze` file to lock, or with --check the lock to audit")
    ap.add_argument("--check", action="store_true",
                    help="audit an existing lock against PyPI instead of writing one")
    args = ap.parse_args(argv)
    if args.check:
        return check(args.input)
    with open(args.input, encoding="utf-8") as fh:
        sys.stdout.write(render(parse_freeze(fh.read())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
