"""What ``--encrypt-root`` COSTS on a cross-built (ARM) image, and whether this host
can pay it.

Ask 21 made root encryption the posture for every image the Studio builds ("root disk
encryption should always be enabled"). On x86 that is cheap: the builder turns
``--encrypt-root`` into ``INSTALLER_ISO=true`` and moves on. On the eight ARM platforms
whose builder HAS an FDE path it is not cheap at all, and the cost is not a warning —
it is a refusal:

* the flag forces the installer artifact on (``${ENCRYPT_ROOT} && BUILD_INSTALLER=true``
  — build-orangepi5-stage4.sh:590 and its six twins; build-rpi5-stage4.sh:1272 sets
  ``BUILD_ISO=true``), so the artifact set of every ARM row CHANGES; and
* the encrypted root needs an **arm64 disk-boot initramfs**, which is generated by
  chrooting into the target sysroot under a static ``qemu-aarch64``. Each ARM builder
  therefore runs a fail-FAST preflight and ``exit 1`` when that is unavailable
  (build-rpi5-stage4.sh:2982-2989, build-orangepi5-stage4.sh:1028-1035,
  build-frite-stage4.sh:1004-1011, build-orangepi-zero2-stage4.sh:1088-1095 and the
  zero2w/zero3/3-lts/4-lts twins). No qemu-aarch64 registration ⇒ the build refuses
  BEFORE it starts.

So an ARM mesh node that built fine before ask 21 now hard-refuses unless the builder
container is ``--privileged`` and ships a static qemu-aarch64. The Studio must say that
where the operator decides, and it can actually CHECK it: ``scripts/_dracut-cross-lib.sh``
documents that "binfmt_misc is KERNEL-GLOBAL, so mounting it inside a container exposes
the host's entries" — the registration this module probes on the host is the same one
the builder container sees.

Qt-free (``core/`` invariant), no network, no subprocess: two file reads.
"""
from __future__ import annotations

import os

from .config import BUILDER_SCRIPTS, PLATFORM_FIELD_SUPPORT

# ── pinned from scripts/_dracut-cross-lib.sh (test_cross_dracut re-reads the shell
# and fails if either constant drifts) ───────────────────────────────────────────────
BINFMT_NODE = "/proc/sys/fs/binfmt_misc/qemu-aarch64"
DEFAULT_INTERP = "/usr/bin/qemu-aarch64"

# The platforms where --encrypt-root drags in the cross-dracut requirement: every
# platform whose builder takes the flag EXCEPT the one that runs natively (x86).
# Computed from the emission table rather than re-listed, so it cannot drift from
# encrypt_root_always()'s own source of truth.
CROSS_FDE_PLATFORMS: tuple[str, ...] = tuple(
    p for p in PLATFORM_FIELD_SUPPORT["encrypt_root"] if p != "x86")

# The builder scripts those platforms dispatch — named here so the drift test can read
# the fail-fast preflight straight out of each one.
CROSS_FDE_BUILDERS: tuple[str, ...] = tuple(
    BUILDER_SCRIPTS[p] for p in CROSS_FDE_PLATFORMS if p in BUILDER_SCRIPTS)


def qemu_interp(node: str = BINFMT_NODE) -> str:
    """The aarch64 interpreter path, mirroring ``dracut_cross_qemu_interp``: the live
    registration's ``^interpreter`` line if there is one, else the pinned default.
    Never raises — an unreadable node degrades to the default."""
    try:
        with open(node, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("interpreter"):
                    parts = line.split()
                    if len(parts) >= 2:
                        return parts[1]
    except OSError:
        pass
    return DEFAULT_INTERP


def preflight_ok(node: str = BINFMT_NODE) -> bool:
    """Mirror of the shell predicate ``dracut_cross_preflight_ok``: qemu-aarch64 is
    registered in binfmt_misc AND its interpreter is executable.

    True here means the ARM FDE path can run; False means the builder must register it
    itself, which only a ``--privileged`` container shipping a static qemu-aarch64 can
    do — and if it cannot, every ARM row exits 1 at its preflight."""
    if not os.path.exists(node):
        return False
    interp = qemu_interp(node)
    return bool(interp) and os.path.isfile(interp) and os.access(interp, os.X_OK)


def cross_fde_rows(rows) -> list[str]:
    """The ids of the ``(id, platform, encrypt_root)`` rows that will hit the ARM
    cross-dracut preflight — i.e. an encrypted root on a cross-built platform. Pure."""
    return [str(rid) for rid, plat, enc in rows
            if enc and (plat or "x86") in CROSS_FDE_PLATFORMS]


# ── the operator-facing text (one wording, used by the Home step AND the Review
# summary, so the two can never say different things) ────────────────────────────────

def cross_fde_note(ids: list[str], ready: bool) -> str:
    """What ask 21 costs on the listed ARM rows, in the operator's terms. Empty when no
    row is affected — this must never become blanket boilerplate on an all-x86 flow."""
    if not ids:
        return ""
    which = ", ".join(ids)
    head = (f"Encrypted root on a cross-built ARM image ({which}): the builder ALSO "
            "produces the installer artifact for each of these (--encrypt-root forces "
            "it on), and the encrypted root needs an arm64 disk-boot initramfs built "
            "under a static qemu-aarch64.")
    if ready:
        tail = ("This host has qemu-aarch64 registered for binfmt "
                f"({qemu_interp()}), which the builder container shares — the "
                "cross-dracut preflight should pass.")
    else:
        tail = ("This host has NO usable qemu-aarch64 binfmt registration, so each of "
                "these rows will REFUSE TO START (exit 1 at the builder's cross-dracut "
                "preflight) unless the build runs in a --privileged container built "
                "with a static qemu-aarch64 (make docker-image). To build them anyway, "
                "set Encryption to 'off' for those rows in the worklist step.")
    return head + " " + tail
