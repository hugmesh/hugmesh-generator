BUILD_ALL_YML = r"""# Build every repository exported for {{DOMAIN}} into the {{ORG}} organisation.
#
# Generated by the HugMesh Studio's Go-Live "Export to GitHub org" step
# (studio/hugmesh_studio/core/org_export.py). The list of repositories
# is repos.json next to this file; regenerate it with another export run rather
# than editing it by hand.
#
# WHAT RUNS. One matrix job per repository: it is checked out with
# actions/checkout (a token input for private repositories — set the
# EXPORT_READ_TOKEN secret to a token that can read every exported repository;
# without it the job's own GITHUB_TOKEN is used, which reads only this repository),
# then built from what the repository ships:
#   java    -> ./mvnw -B -s .github/maven-ci-settings.xml verify
#              (repos.json says which settings file a repository has; the
#              repository-root settings.xml is the GitLab registry file and is not
#              passed. The settings file reads UPSTREAM_PACKAGES_ACTOR and
#              UPSTREAM_PACKAGES_TOKEN, set below from PACKAGES_READ_ACTOR /
#              PACKAGES_READ_TOKEN. The private library chain only resolves once the
#              exported libraries' own release workflows have published to this
#              organisation's registry.)
#   angular -> npm ci, npm run build, npm test    (Karma on ChromeHeadlessCI)
#   none    -> nothing to build here (its own CI, if any, is the gate)
# This follows the repositories' release.yml and package files; the org holds no
# composite actions to call instead.
#
# RUNS_ON is the repository variable the org's workflows use for a self-hosted
# runner (a JSON runner spec); unset, every job runs on ubuntu-latest.
name: Build all exported repositories

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: build-all-${{ github.ref }}
  cancel-in-progress: true

env:
  NODE_VERSION: '24'
  JAVA_VERSION: '25'

jobs:
  repos:
    name: List the exported repositories
    runs-on: ${{ fromJSON(vars.RUNS_ON || '"ubuntu-latest"') }}
    outputs:
      matrix: ${{ steps.list.outputs.matrix }}
      count: ${{ steps.list.outputs.count }}
    steps:
      - uses: actions/checkout@v4
      - id: list
        run: |
          set -eu
          matrix="$(jq -c '{include: [.repos[] | {name: .name, build: .build, settings: .settings}]}' repos.json)"
          count="$(jq '.repos | length' repos.json)"
          echo "matrix=${matrix}" >> "$GITHUB_OUTPUT"
          echo "count=${count}" >> "$GITHUB_OUTPUT"
          echo "${count} repositories listed in repos.json"

  build:
    name: ${{ matrix.name }} (${{ matrix.build }})
    needs: repos
    if: needs.repos.outputs.count != '0'
    runs-on: ${{ fromJSON(vars.RUNS_ON || '"ubuntu-latest"') }}
    strategy:
      fail-fast: false
      matrix: ${{ fromJSON(needs.repos.outputs.matrix) }}
    steps:
      - name: Check out {{ORG}}/${{ matrix.name }}
        uses: actions/checkout@v4
        with:
          repository: {{ORG}}/${{ matrix.name }}
          token: ${{ secrets.EXPORT_READ_TOKEN || github.token }}
          path: src

      # ---------------------------------------------------------------- java
      - name: Set up Java
        if: matrix.build == 'java'
        uses: actions/setup-java@v4
        with:
          distribution: temurin
          java-version: ${{ env.JAVA_VERSION }}
      - name: Maven verify (tests, PMD, Checkstyle, SpotBugs — never skipped)
        if: matrix.build == 'java'
        working-directory: src
        env:
          # the names .github/maven-ci-settings.xml reads. No fall-back to the job
          # token: it cannot read another repository's package, and an empty token
          # would only fail later as an unresolvable parent POM
          UPSTREAM_PACKAGES_ACTOR: ${{ secrets.PACKAGES_READ_ACTOR || github.actor }}
          UPSTREAM_PACKAGES_TOKEN: ${{ secrets.PACKAGES_READ_TOKEN }}
          MAVEN_SETTINGS: ${{ matrix.settings }}
        run: |
          set -eu
          if [ -n "${MAVEN_SETTINGS}" ]; then
            if [ "${MAVEN_SETTINGS}" = ".github/maven-ci-settings.xml" ] && [ -z "${UPSTREAM_PACKAGES_TOKEN}" ]; then
              echo "::error::secret PACKAGES_READ_TOKEN is not set: Maven cannot read the private libraries from this organisation's package registry"
              exit 1
            fi
            ./mvnw -B -s "${MAVEN_SETTINGS}" verify
          else
            ./mvnw -B verify
          fi

      # ------------------------------------------------------------- angular
      - name: Set up Node
        if: matrix.build == 'angular'
        uses: actions/setup-node@v4
        with:
          node-version: ${{ env.NODE_VERSION }}
      - name: npm ci
        if: matrix.build == 'angular'
        working-directory: src
        run: npm ci --no-audit --no-fund
      - name: npm run build
        if: matrix.build == 'angular'
        working-directory: src
        run: npm run build
      - name: Locate a headless Chrome
        if: matrix.build == 'angular'
        run: |
          set -eu
          for c in /usr/bin/google-chrome /usr/bin/google-chrome-stable \
                   /usr/bin/chromium /usr/bin/chromium-browser; do
            if [ -x "$c" ]; then
              echo "CHROME_BIN=$c" >> "$GITHUB_ENV"
              echo "using $c"
              "$c" --version || true
              exit 0
            fi
          done
          echo "::error::no Chrome binary on this runner image; karma cannot launch ChromeHeadlessCI"
          exit 1
      - name: npm test (Karma, ChromeHeadlessCI)
        if: matrix.build == 'angular'
        working-directory: src
        run: npm test

      - name: Nothing to build
        if: matrix.build == 'none'
        run: echo "${{ matrix.name }} has no Maven or Angular build; its own CI is the gate."
"""

PAGES_YML = r"""# Publish this repository as the GitHub Pages site of {{DOMAIN}}.
#
# Generated by the HugMesh Studio's Go-Live "Export to GitHub org" step.
# Separate from build-all.yml on purpose, the way the org's docs site
# keeps its deploy apart from its gates: this workflow needs `pages: write` and
# `id-token: write`, and nothing that runs untrusted code should hold those.
#
# Pages must be enabled on this repository (Settings -> Pages -> Source: GitHub
# Actions) before the deploy job can succeed; the first run says so if it is not.
name: Deploy Pages

on:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: false

jobs:
  build:
    name: Assemble the site
    runs-on: ${{ fromJSON(vars.RUNS_ON || '"ubuntu-latest"') }}
    steps:
      - uses: actions/checkout@v4
      - name: Assemble
        run: |
          set -eu
          mkdir -p _site
          cp index.html repos.json README.md _site/
          ls -l _site
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v3
        with:
          path: _site

  deploy:
    name: Deploy
    needs: build
    runs-on: ${{ fromJSON(vars.RUNS_ON || '"ubuntu-latest"') }}
    environment:
      name: github-pages
      url: ${{ steps.deployment.outputs.page_url }}
    steps:
      - id: deployment
        uses: actions/deploy-pages@v4
"""

