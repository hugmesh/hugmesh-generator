"""The "Add user…" dialog — ONE named account for the RUNNING local mesh.

Qt half only. The dialog COLLECTS (name, email, password, roles); the page's
``_add_user`` verb applies through ``core.mesh_accounts``: straight through Casdoor's
admin API on the compose lane (the mesh's central sign-in) and through the kind lane's
casdoor door on kind — never the e2e seeder, so it works from any checkout and never
touches the e2e personas or their shared password (2026-11-19, the operator: "adding
users should work without the e2e scripts"). A domain's own people are added on that
domain's Users tab (Brand settings), which uses the same core.

Validation is ``mesh_accounts.username_problem`` / ``password_problem``, the same rules
the apply enforces, so the dialog can never hand the verb a value it would refuse.
ROLE_USER is forced-checked — the gateway floor requires it. An empty password is
generated by the apply and shown once on the page's status line (never logged).
"""
from __future__ import annotations

from ..qt import QtCore, QtWidgets
from ...core import mesh_accounts
from ...core.seeded_credentials import ROLE_APPS


class AddUserDialog(QtWidgets.QDialog):
    def __init__(self, generator_dir: str, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Add a user to this mesh")
        self.setModal(True)
        lay = QtWidgets.QVBoxLayout(self)

        intro = QtWidgets.QLabel(
            "Creates ONE named account in the running mesh's sign-in (Casdoor), "
            "directly through its admin API: no seeder runs and no other account is "
            "touched. A name that already exists is refused, never re-passworded. "
            "A domain's own people are added on that domain's Users tab (Brand "
            "settings).")
        intro.setWordWrap(True)
        lay.addWidget(intro)

        form = QtWidgets.QFormLayout()
        self.username = QtWidgets.QLineEdit()
        self.username.setPlaceholderText("letters/digits, - or _ inside")
        self.username.textChanged.connect(self._revalidate)
        form.addRow("Username", self.username)

        self.email = QtWidgets.QLineEdit()
        self.email.setPlaceholderText("optional")
        form.addRow("Email", self.email)

        self.password = QtWidgets.QLineEdit()
        self.password.setEchoMode(QtWidgets.QLineEdit.EchoMode.Password)
        self.password.setPlaceholderText("empty: one is made and shown once")
        self.password.textChanged.connect(self._revalidate)
        form.addRow("Password", self.password)
        lay.addLayout(form)

        lay.addWidget(QtWidgets.QLabel("Roles:"))
        self._role_boxes: list[tuple[str, QtWidgets.QCheckBox]] = []
        for role in mesh_accounts.GRANTABLE_ROLES:
            label = role
            app = ROLE_APPS.get(role)
            if app:
                label = f"{role}  (opens {app})"
            box = QtWidgets.QCheckBox(label)
            if role == mesh_accounts.FLOOR_ROLE:
                # The gateway floor: every principal needs it; not optional.
                box.setChecked(True)
                box.setEnabled(False)
            box.toggled.connect(self._revalidate)
            self._role_boxes.append((role, box))
            lay.addWidget(box)

        self.err = QtWidgets.QLabel("")
        self.err.setWordWrap(True)
        self.err.setStyleSheet("color: #c62828;")
        self.err.setVisible(False)
        lay.addWidget(self.err)

        btns = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Ok
            | QtWidgets.QDialogButtonBox.StandardButton.Cancel)
        btns.accepted.connect(self.accept)
        btns.rejected.connect(self.reject)
        self._ok = btns.button(QtWidgets.QDialogButtonBox.StandardButton.Ok)
        self._ok.setEnabled(False)
        lay.addWidget(btns)

    # ── validation (never raises: slots) ─────────────────────────────────────────
    def _username_error(self) -> str:
        return (mesh_accounts.username_problem(self.username.text())
                or (mesh_accounts.password_problem(self.password.text())
                    if self.password.text() else ""))

    def _revalidate(self, *_):
        err = self._username_error()
        self.err.setText(err)
        self.err.setVisible(bool(err))
        self._ok.setEnabled(not err)

    # ── result ───────────────────────────────────────────────────────────────────
    def result_values(self) -> tuple[str, tuple[str, ...], str, str]:
        """(username, roles, password, email). The password ("" = generate one) goes
        to the apply's request body only: never argv, never a log line."""
        roles = tuple(r for r, box in self._role_boxes if box.isChecked())
        return (self.username.text().strip(), roles, self.password.text(),
                self.email.text().strip())
