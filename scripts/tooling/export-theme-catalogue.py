#!/usr/bin/env python3
"""Export the theme preset catalogue for consumers outside this repo.

hugmesh-admin-ui's per-domain theme editor offers presets by name, but the catalogue
lives here (studio/hugmesh_studio/core/theme_presets.PRESETS). It vendors this file's
output as src/app/themes/theme-catalogue.ts; re-run and re-vendor when the catalogue
or the ramps change:

    python3 scripts/tooling/export-theme-catalogue.py > ../hugmesh-admin-ui/src/app/themes/theme-catalogue.ts
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "studio"))
from hugmesh_studio.core import theme_presets as tp  # noqa: E402

rows = [{"id": p.preset_id, "label": p.label, "group": p.group,
         "effect": p.effect or "gradient", "font": p.font} for p in tp.PRESETS]
print("// GENERATED by hugmesh-generator scripts/tooling/export-theme-catalogue.py from")
print("// studio/hugmesh_studio/core/theme_presets.PRESETS. Do not edit by hand: re-export.")
print("export interface ThemePresetEntry {")
print("  readonly id: string;\n  readonly label: string;\n  readonly group: string;")
print("  readonly effect: string;\n  readonly font: string;\n}")
print(f"export const THEME_RAMPS = {json.dumps(list(tp.MODES))} as const;")
print("export const THEME_PRESETS: readonly ThemePresetEntry[] = [")
for r in rows:
    print("  " + json.dumps(r, ensure_ascii=False) + ",")
print("];")
