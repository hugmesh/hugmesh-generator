#!/usr/bin/env bash
# selinux-make-auditallow.sh — build the instrument that can NARROW an
# INFERRED-WIDE rule.
#
# WHY THIS EXISTS. docs/selinux-module-loading.md says to "collect the
# permissive-pass AVCs to narrow every rule tagged INFERRED-WIDE". That cannot
# work, and the distinction is the whole point:
#
#   an AVC DENIAL is raised for something the policy does NOT allow
#       -> it tells you what to ADD
#   narrowing an over-broad `allow` needs what WAS ACTUALLY EXERCISED
#       -> that is an auditallow record (type=AVC ... granted=)
#
# Measured: with six modules loaded and the full workload driven, a permissive
# run produced ZERO denials — correctly, because the rules are deliberately wide.
# A wide rule denies nothing, so denial-collection can never narrow it.
#
# WHY CIL AND NOT THE .te. Only 12 of the 59 INFERRED-WIDE lines are raw `allow`
# statements a generator could mirror directly; 28 are interface calls
# (corenet_tcp_connect_all_ports(...), files_read_non_auth_files(...)) that expand
# inside an m4 macro into rules this script would have to re-derive. A compiled
# .pp converted back to CIL is POST-EXPANSION, so it carries every rule the module
# really grants — hugmesh_vpn alone expands from 19 tagged lines to 224 allow
# rules. Transforming that is a textual `(allow` -> `(auditallow`, with no policy
# language to re-implement and nothing to get subtly wrong.
#
# USAGE
#   scripts/selinux-make-auditallow.sh --pp-tool <path/to/hll/pp> \
#       [--prefix hugmesh_] <module.pp> [<module.pp> ...] > narrow.cil
#   (in the guest)  semodule -s mcs -i narrow.cil
#   ... drive the workload ...
#   ausearch -m AVC | grep 'granted=' -> exactly what each wide rule really used
#
# The emitted module ONLY adds auditallow. It grants nothing, denies nothing and
# changes no decision — it makes granted accesses visible. Remove it when done.
set -uo pipefail

PROG="$(basename "$0")"
die() { echo "${PROG}: error: $*" >&2; exit 2; }

PP_TOOL=""; PREFIX="hugmesh_"; MODNAME="hugmesh_narrow"
PPS=()
while [ $# -gt 0 ]; do
    case "$1" in
        --pp-tool)  PP_TOOL="$2"; shift 2 ;;
        --prefix)   PREFIX="$2"; shift 2 ;;
        --name)     MODNAME="$2"; shift 2 ;;
        -h|--help)  sed -n '2,40p' "$0"; exit 0 ;;
        -*)         die "unknown option $1" ;;
        *)          PPS+=("$1"); shift ;;
    esac
done
[ "${#PPS[@]}" -gt 0 ] || die "no .pp given. See --help."

if [ -z "${PP_TOOL}" ]; then
    for c in /usr/libexec/selinux/hll/pp /usr/lib/selinux/hll/pp; do
        [ -x "${c}" ] && { PP_TOOL="${c}"; break; }
    done
fi
[ -n "${PP_TOOL}" ] && [ -x "${PP_TOOL}" ] \
    || die "no pp (high-level-language) converter found; pass --pp-tool <path>"

emitted=0
{
    echo ";; ${MODNAME} — auditallow mirror of every rule the ${PREFIX}* modules grant."
    echo ";; Generated by scripts/${PROG}. Grants nothing; makes GRANTED accesses"
    echo ";; visible so an INFERRED-WIDE rule can be narrowed to what it really uses."
    for pp in "${PPS[@]}"; do
        [ -f "${pp}" ] || die "no such .pp: ${pp}"
        cil="$("${PP_TOOL}" < "${pp}" 2>/dev/null)" || die "pp conversion failed for ${pp}"
        [ -n "${cil}" ] || die "pp produced no CIL for ${pp} — refusing to emit an empty instrument"
        n=0
        while IFS= read -r line; do
            # Only rules whose SOURCE is one of our domains. Auditing what the
            # base policy grants everything else would bury the signal.
            case "${line}" in
                "(allow ${PREFIX}"*) ;;
                *) continue ;;
            esac
            printf '%s\n' "${line/(allow /(auditallow }"
            n=$((n+1))
        done <<< "${cil}"
        echo ";; ${pp##*/}: ${n} rule(s)" >&2
        emitted=$((emitted+n))
    done
} 
[ "${emitted}" -gt 0 ] || die "emitted 0 auditallow rules — nothing would be observed, which is not a usable instrument"
echo ";; total: ${emitted} auditallow rule(s)" >&2
