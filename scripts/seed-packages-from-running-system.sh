#!/usr/bin/env bash
# seed-packages-from-running-system.sh — emit a Snapdragon package list from THIS
# running Gentoo box's explicitly-installed set (/var/lib/portage/world), so a
# generated desktop image can "copy all installed programs" from the host.
#
# Output is a plain atom-per-line list (with metadata comments) suitable for:
#   ./build-x86-host-stage4.sh --role standalone-thick --seed-packages-from out.list
#
# It is a read-only, ad-hoc helper — it never changes the running system.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GREEN=$'\033[0;32m'; YEL=$'\033[0;33m'; RED=$'\033[0;31m'; RST=$'\033[0m'
info(){ echo "${GREEN}    $*${RST}"; }
warn(){ echo "${YEL}    WARNING: $*${RST}" >&2; }
err(){  echo "${RED}    ERROR: $*${RST}" >&2; }

WORLD="/var/lib/portage/world"
MAKECONF="/etc/portage/make.conf"
OUTPUT=""
CONSERVATIVE=false       # drop heavy desktop/media/dev categories
EXCLUDE_NVIDIA=false     # drop nvidia atoms (e.g. seeding a non-GPU target)
WITH_USE=true            # include VIDEO_CARDS/USE/ACCEPT_LICENSE hints as comments

usage(){ cat <<EOF
Usage: $0 [--output FILE] [--world FILE] [--conservative] [--exclude-nvidia] [--no-use-hints]
  --output FILE       Write the list here (default: stdout).
  --world FILE         Source world file (default: ${WORLD}).
  --conservative      Exclude desktop/media/dev-heavy categories (lean seed).
  --exclude-nvidia    Drop x11-drivers/nvidia-drivers + nvidia-cuda atoms.
  --no-use-hints      Don't emit the make.conf VIDEO_CARDS/USE/ACCEPT_LICENSE comments.
EOF
exit "${1:-0}"; }

while [ $# -gt 0 ]; do
    case "$1" in
        --output) OUTPUT="$2"; shift 2 ;;
        --world) WORLD="$2"; shift 2 ;;
        --conservative) CONSERVATIVE=true; shift ;;
        --exclude-nvidia) EXCLUDE_NVIDIA=true; shift ;;
        --no-use-hints) WITH_USE=false; shift ;;
        -h|--help) usage 0 ;;
        *) err "unknown option: $1"; usage 1 ;;
    esac
done

[ -r "${WORLD}" ] || { err "world file not readable: ${WORLD}"; exit 1; }

# Categories dropped in --conservative (a leaner seed).
CONSERVATIVE_DROP='^(kde-apps|kde-plasma|media-gfx|media-sound|media-video|games-|app-office|net-im)'

emit(){
    grep -vE '^\s*(#|$)' "${WORLD}" | sort -u | while read -r atom; do
        ${EXCLUDE_NVIDIA} && [[ "${atom}" =~ nvidia ]] && continue
        ${CONSERVATIVE} && [[ "${atom}" =~ ${CONSERVATIVE_DROP} ]] && continue
        # Strip any leading version operators/slot — emit the bare category/pkg.
        echo "${atom}" | sed -E 's/^[<>=~]+//; s/:[^ ]*$//'
    done | sort -u
}

write_list(){
    echo "# Seeded from $(hostname 2>/dev/null || echo this-host):${WORLD}"
    echo "# Generated by scripts/seed-packages-from-running-system.sh"
    if ${WITH_USE} && [ -r "${MAKECONF}" ]; then
        echo "# --- make.conf hints (copy into brand.conf / make.conf.tmpl as needed) ---"
        grep -E '^\s*(VIDEO_CARDS|ACCEPT_LICENSE|USE)=' "${MAKECONF}" 2>/dev/null | sed 's/^/#   /' || true
        echo "# -------------------------------------------------------------------------"
    fi
    emit
}

n=$(emit | wc -l)
if [ -n "${OUTPUT}" ]; then
    write_list > "${OUTPUT}"
    info "Wrote ${n} atoms to ${OUTPUT}"
    info "Use: ./build-x86-host-stage4.sh --role standalone-thick --seed-packages-from ${OUTPUT}"
else
    write_list
fi
