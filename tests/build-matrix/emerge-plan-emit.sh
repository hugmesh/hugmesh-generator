#!/usr/bin/env bash
# emerge-plan-emit.sh — EXECUTED test of scripts/_emerge-plan-lib.sh (the plan-preview
# emission every builder runs before its multi-package emerge groups). Rendered-output
# grep is NOT enough for a block that must never break a build, so this actually RUNS
# emerge_plan_emit against stub emerges and asserts, byte-for-byte:
#
#   * the exact wire format over REAL captured portage rows — the 30 [ebuild rows in
#     fixtures/emerge-pretend-plan.real.txt are verbatim from the operator's own build
#     (out/sessions/20260730-061622-abaf4b/build-pki.x86.log:57221-57250, trailing
#     spaces included); the --pretend framing (header/Total) is portage's canonical
#     pretend shape. The golden wire files were generated by an INDEPENDENT python
#     reimplementation at authoring time and hand-checked, so lib-awk and golden
#     cannot share a bug by construction.
#   * edge shapes (fixtures/emerge-pretend-plan.edge.txt, synthetic and labeled so):
#     ::repo strip, cross-merge " to /sysroot/" tails, [binary rows, ANSI codes,
#     portage's %/* flag markers, no-USE rows, [uninstall]/[blocks] tolerance.
#   * READ-ONLY: the stub refuses (exit 99 + marker) unless --pretend is in argv, and
#     the argv is recorded so the appended safety options are pinned.
#   * CMD-may-be-a-function: the same golden run through a cross_emerge-style wrapper
#     function (why the lib's timeout is a hand-rolled watchdog).
#   * the opt-out (--no-emerge-plan => EMERGE_PLAN_ENABLED=false): one opt-out line,
#     resolver NEVER invoked.
#   * failure tolerance: resolution failure, watchdog timeout, and parse drift each
#     emit their 'unavailable reason=' shape and return 0 — including under the x86
#     chroot's `bash -eo pipefail`, where a nonzero return would abort the payload.
#
# No root, no writes outside mktemp, never touches real portage. Run directly or via
# tests/build-matrix/check.sh (EPL bucket):
#   bash tests/build-matrix/emerge-plan-emit.sh
set -u

TEST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "${TEST_DIR}/../.." && pwd)"
FIX_DIR="${TEST_DIR}/fixtures"

TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
# Sandbox the lib's keep-file side channel (the pretend-failed resolver output
# it preserves for the x86 payload gate, issue #223) into ${TMP}, so this test
# neither leaks files into the real /tmp nor collides with a parallel run.
export TMPDIR="${TMP}"

FAILS=0
pass() { printf 'EPLT PASS %s\n' "$1"; }
fail() { printf 'EPLT FAIL %s: %s\n' "$1" "$2"; FAILS=$((FAILS + 1)); }

# shellcheck source=../../scripts/_emerge-plan-lib.sh
source "${REPO_DIR}/scripts/_emerge-plan-lib.sh"

# ── stubs ──────────────────────────────────────────────────────────────────────
# Each records its argv and REFUSES to run without --pretend (a lib regression that
# dropped --pretend would otherwise silently run a REAL emerge on a builder).
mk_stub() { # NAME BODY-AFTER-GUARD
    cat >"${TMP}/$1" <<STUB
#!/bin/sh
printf '%s\n' "\$@" > "${TMP}/argv.$1"
case " \$* " in
  *" --pretend "*) : ;;
  *) : > "${TMP}/MERGE-ATTEMPT.$1"; exit 99 ;;
esac
$2
STUB
    chmod +x "${TMP}/$1"
}
mk_stub emerge-real "cat '${FIX_DIR}/emerge-pretend-plan.real.txt'"
mk_stub emerge-edge "cat '${FIX_DIR}/emerge-pretend-plan.edge.txt'"
mk_stub emerge-fail "echo 'emerge: error: it broke' >&2; exit 3"
mk_stub emerge-slow "exec sleep 30"
mk_stub emerge-drift "printf 'Calculating dependencies  ... done!\n\nTotal: 5 packages (5 new), Size of downloads: 1 KiB\n'"

# ── 1. exact wire format over the REAL captured rows ──────────────────────────
emerge_plan_emit image "${TMP}/emerge-real" --update --deep --newuse --keep-going @world \
    >"${TMP}/out.real" 2>"${TMP}/err.real"
rc=$?
if [ ${rc} -ne 0 ]; then
    fail wire-real "returned ${rc}, not 0"
elif ! diff -u "${FIX_DIR}/emerge-plan-wire.real.txt" \
        <(grep '^==> Emerge plan: ' "${TMP}/out.real") >"${TMP}/diff.real" 2>&1; then
    fail wire-real "wire output diverged from the golden: $(head -3 "${TMP}/diff.real" | tr '\n' ' ')"
else
    pass wire-real
fi

# ── 2. read-only + argv pinning: SAME caller argv verbatim, safety opts appended ─
if [ -e "${TMP}/MERGE-ATTEMPT.emerge-real" ]; then
    fail read-only "the stub was invoked WITHOUT --pretend (a real merge would have run)"
else
    pass read-only
fi
want_argv="$(printf '%s\n' --update --deep --newuse --keep-going @world \
    --pretend --color=n --nospinner --autounmask-write=n)"
if [ "$(cat "${TMP}/argv.emerge-real")" = "${want_argv}" ]; then
    pass argv-parity
else
    fail argv-parity "argv drifted: $(tr '\n' ' ' < "${TMP}/argv.emerge-real")"
fi

# ── 3. edge shapes (::repo, cross tails, [binary, ANSI, %/* markers, blocks) ──
emerge_plan_emit image "${TMP}/emerge-edge" pkg >"${TMP}/out.edge" 2>/dev/null
if diff -q "${FIX_DIR}/emerge-plan-wire.edge.txt" \
        <(grep '^==> Emerge plan: ' "${TMP}/out.edge") >/dev/null 2>&1; then
    pass wire-edge
else
    fail wire-edge "edge wire diverged: $(diff "${FIX_DIR}/emerge-plan-wire.edge.txt" \
        <(grep '^==> Emerge plan: ' "${TMP}/out.edge") 2>&1 | head -2 | tr '\n' ' ')"
fi

# ── 3b. binpkg reuse line (issue #46): one human line per planned group, read
#        back off the wire's own total line, so it can never disagree with it ──
want_edge='[emerge-plan] image binpkg reuse: 1 of 5 package(s) from the pool (20%), 4 to compile'
want_real='[emerge-plan] image binpkg reuse: 0 of 30 package(s) from the pool (0%), 30 to compile'
if [ "$(grep -F 'binpkg reuse:' "${TMP}/out.edge")" = "${want_edge}" ] \
   && [ "$(grep -F 'binpkg reuse:' "${TMP}/out.real")" = "${want_real}" ]; then
    pass reuse-line
else
    fail reuse-line "expected '${want_edge}' / '${want_real}', got: $(grep -hF 'binpkg reuse:' "${TMP}/out.edge" "${TMP}/out.real" | tr '\n' '|')"
fi
# ...and a group with nothing to merge says so rather than claiming a 0% rate.
mk_stub emerge-empty "printf 'Calculating dependencies  ... done!\n\nTotal: 0 packages, Size of downloads: 0 KiB\n'"
emerge_plan_emit image "${TMP}/emerge-empty" @world >"${TMP}/out.empty" 2>/dev/null
if [ "$(grep '^==> Emerge plan: ' "${TMP}/out.empty")" = "==> Emerge plan: image total=0 binary=0 ebuild=0" ] \
   && [ "$(grep -F 'binpkg reuse:' "${TMP}/out.empty")" = "[emerge-plan] image binpkg reuse: nothing to merge" ]; then
    pass reuse-line-empty
else
    fail reuse-line-empty "unexpected output: $(cat "${TMP}/out.empty" | tr '\n' '|')"
fi

# ── 4. CMD may be a shell FUNCTION (the cross_emerge shape) ───────────────────
fake_cross_emerge() { "${TMP}/emerge-real" --jobs=1 --with-bdeps=n "$@"; }
emerge_plan_emit system fake_cross_emerge --update @system >"${TMP}/out.fn" 2>/dev/null
if diff -q <(sed 's/^==> Emerge plan: image/==> Emerge plan: system/' \
            "${FIX_DIR}/emerge-plan-wire.real.txt") \
        <(grep '^==> Emerge plan: ' "${TMP}/out.fn") >/dev/null 2>&1; then
    pass function-cmd
else
    fail function-cmd "wire through a wrapper function diverged"
fi

# ── 5. opt-out: one honest line, resolver NEVER invoked ───────────────────────
rm -f "${TMP}/argv.emerge-real"
EMERGE_PLAN_ENABLED=false emerge_plan_emit image "${TMP}/emerge-real" @world >"${TMP}/out.opt" 2>/dev/null
rc=$?
if [ ${rc} -ne 0 ]; then
    fail opt-out "returned ${rc}, not 0"
elif [ "$(cat "${TMP}/out.opt")" != "==> Emerge plan: image unavailable reason=opt-out" ]; then
    fail opt-out "unexpected output: $(cat "${TMP}/out.opt")"
elif [ -e "${TMP}/argv.emerge-real" ]; then
    fail opt-out "the resolver was invoked despite the opt-out"
else
    pass opt-out
fi

# ── 6. resolution failure => unavailable + return 0 (never breaks a build) ────
emerge_plan_emit world "${TMP}/emerge-fail" @world >"${TMP}/out.fail" 2>"${TMP}/err.fail"
rc=$?
if [ ${rc} -ne 0 ]; then
    fail tolerate-failure "returned ${rc}, not 0"
elif [ "$(grep '^==> Emerge plan: ' "${TMP}/out.fail")" != "==> Emerge plan: world unavailable reason=pretend-failed" ]; then
    fail tolerate-failure "unexpected output: $(cat "${TMP}/out.fail")"
elif ! grep -q 'WARN' "${TMP}/err.fail"; then
    fail tolerate-failure "no WARN on stderr"
else
    pass tolerate-failure
fi

# ── 6b. pretend-failed KEEPS the resolver output for the payload gate (#223) ──
# The x86 builder's hugmesh_payload_plan_gate reads this file to fail fast on
# keyword/mask walls the real merge (--autounmask-keep-keywords=y) cannot cross.
keepf="${TMPDIR:-/tmp}/hugmesh-emerge-plan-world-pretend-failed.log"
if [ -f "${keepf}" ] && grep -q 'it broke' "${keepf}"; then
    pass keep-file
else
    fail keep-file "pretend-failed did not keep the resolver output at ${keepf}"
fi
# ...and a following SUCCESSFUL plan for the same group must CLEAR the stale
# keep-file (resumed sysroots persist /tmp — a stale file would trip the gate
# on a plan that resolved).
emerge_plan_emit world "${TMP}/emerge-real" @world >/dev/null 2>&1
if [ -f "${keepf}" ]; then
    fail keep-file-clear "a resolved plan left a stale pretend-failed keep-file behind"
else
    pass keep-file-clear
fi

# ── 7. watchdog timeout => unavailable + return 0 (stub sleeps 30, budget 2s) ─
EMERGE_PLAN_TIMEOUT=2 emerge_plan_emit image "${TMP}/emerge-slow" @world >"${TMP}/out.slow" 2>/dev/null
rc=$?
if [ ${rc} -ne 0 ]; then
    fail tolerate-timeout "returned ${rc}, not 0"
elif [ "$(grep '^==> Emerge plan: ' "${TMP}/out.slow")" != "==> Emerge plan: image unavailable reason=pretend-timeout" ]; then
    fail tolerate-timeout "unexpected output: $(cat "${TMP}/out.slow")"
else
    pass tolerate-timeout
fi

# ── 8. row/Total drift => parse-mismatch, an honest nothing over a fabricated list ─
emerge_plan_emit image "${TMP}/emerge-drift" @world >"${TMP}/out.drift" 2>/dev/null
if [ "$(grep '^==> Emerge plan: ' "${TMP}/out.drift")" = "==> Emerge plan: image unavailable reason=parse-mismatch" ]; then
    pass tolerate-drift
else
    fail tolerate-drift "unexpected output: $(cat "${TMP}/out.drift")"
fi

# ── 9. the x86 contract: survives `bash -eo pipefail` even when everything fails ─
if bash -eo pipefail -c "
    source '${REPO_DIR}/scripts/_emerge-plan-lib.sh'
    emerge_plan_emit world '${TMP}/emerge-fail' @world
    EMERGE_PLAN_TIMEOUT=2 emerge_plan_emit world '${TMP}/emerge-slow' @world
    emerge_plan_emit world '${TMP}/emerge-drift' @world
    EMERGE_PLAN_ENABLED=false emerge_plan_emit world '${TMP}/emerge-real' @world
    echo SURVIVED" >"${TMP}/out.strict" 2>/dev/null \
   && grep -q '^SURVIVED$' "${TMP}/out.strict"; then
    pass strict-shell
else
    fail strict-shell "a failure path aborted under bash -eo pipefail (would kill the x86 payload chroot)"
fi

if [ "${FAILS}" -eq 0 ]; then
    echo "emerge-plan-emit: ALL PASS"
    exit 0
fi
echo "emerge-plan-emit: ${FAILS} FAILURE(S)" >&2
exit 1
