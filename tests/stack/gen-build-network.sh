#!/usr/bin/env bash
# gen-build-network.sh <out.yaml> <the compose arguments of the run: -f files, --env-file, ...>
#
# Writes a compose overlay that gives EVERY service that has a `build:` the build network
# $BUILD_NETWORK (host|none|default; buildkit accepts nothing else). `make stack-up BUILD_NETWORK=host`
# includes it. Why: the docker bridge's MTU/DNS trap stalls or drops name lookups inside image builds
# (UnknownHostException on repo.maven.apache.org while the same name resolves on the host), and compose
# has no global switch for the build network, only a per-service `build.network`.
#
# The service list comes from compose itself (`config --no-interpolate --profile '*'`), so it follows
# the compose files and profiles instead of a hand-kept list that would go stale.
set -euo pipefail
out="${1:?usage: gen-build-network.sh <out.yaml> <compose args>...}"; shift
net="${BUILD_NETWORK:?BUILD_NETWORK is not set}"
case "${net}" in host|none|default) ;; *)
  echo "BUILD_NETWORK='${net}': buildkit accepts only host, none or default." >&2; exit 2 ;; esac
command -v jq >/dev/null || { echo "gen-build-network.sh: jq is required" >&2; exit 2; }
args=("$@")   # the run's own -f list: a service the run does not define must not appear in the overlay
svcs="$(docker compose "${args[@]}" --profile '*' config --no-interpolate --format json \
          | jq -r '.services | to_entries[] | select(.value.build != null) | .key' | sort)"
[ -n "${svcs}" ] || { echo "gen-build-network.sh: no service with a build: in the given compose files" >&2; exit 1; }
tmp="$(mktemp "${out}.XXXXXX")"
{
  echo "# GENERATED by tests/stack/gen-build-network.sh (BUILD_NETWORK=${net}); gitignored, rewritten on every stack-up."
  echo "services:"
  while IFS= read -r s; do printf '  %s:\n    build:\n      network: %s\n' "${s}" "${net}"; done <<<"${svcs}"
} >"${tmp}"
mv -f "${tmp}" "${out}"
echo "==> BUILD_NETWORK=${net}: $(wc -l <<<"${svcs}" | tr -d ' ') services build on it (${out})"
