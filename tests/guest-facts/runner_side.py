"""Runner-side half of the guest host-facts experiment (hugmesh-generator#1048).

Runs on the ubuntu-latest runner, never in a guest. Two modes:

  image      after the VM action ran: record what the guest booted FROM. The
             action, its pinned commit and the release are written as given; the
             image files anyvm downloaded into --data-dir and the anyvm.py it
             fetched are hashed here, on the runner, so the digest is measured,
             never copied from a README. The action boots with --snapshot, so the
             qcow2 in --data-dir is the downloaded image, unmodified by the run.

                 python3 tests/guest-facts/runner_side.py image --out DIR \\
                     --action vmactions/freebsd-vm@SHA --release 15.1 \\
                     --data-dir "$RUNNER_TEMP/vm-data" --actions-dir "$RUNNER_WORKSPACE/../_actions"

  summarize  after every guest job: read the per-guest fixture directories and
             write SUMMARY.md (which install line worked, per guest; the DragonFly
             statement; the contract sizing) and contract-list.txt (the files that
             were green on EVERY guest whose sizing run finished).

                 python3 tests/guest-facts/runner_side.py summarize --root FIXTURES

Every value in SUMMARY.md is read from a fixture file; a guest whose files are
missing is reported as missing, never filled in.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import os
import sys

GUESTS = ("freebsd", "openbsd", "netbsd", "dragonfly", "solaris", "omnios", "openindiana")
MIN_IMAGE_BYTES = 1 << 20


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def image(out: str, action: str, release: str, data_dir: str, actions_dir: str) -> int:
    os.makedirs(out, exist_ok=True)
    rows = []
    for root, _dirs, files in os.walk(data_dir):
        for name in sorted(files):
            path = os.path.join(root, name)
            if os.path.islink(path) or os.path.getsize(path) < MIN_IMAGE_BYTES:
                continue
            rows.append(("image", os.path.relpath(path, data_dir), os.path.getsize(path), _sha256(path)))
    repo, _, sha = action.partition("@")
    owner_repo_dir = os.path.join(actions_dir, *repo.split("/"), sha)
    for root, _dirs, files in os.walk(owner_repo_dir):
        for name in files:
            if name == "anyvm.py":
                path = os.path.join(root, name)
                rows.append(("anyvm.py", os.path.relpath(path, owner_repo_dir), os.path.getsize(path), _sha256(path)))
    with open(os.path.join(out, "image.tsv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, delimiter="\t", lineterminator="\n")
        w.writerow(["kind", "path", "bytes", "sha256"])
        w.writerow(["action", action, "", ""])
        w.writerow(["release", release, "", ""])
        for row in rows:
            w.writerow(row)
    if not any(r[0] == "image" for r in rows):
        print(f"runner_side: no image file of {MIN_IMAGE_BYTES}+ bytes under {data_dir}", file=sys.stderr)
        return 1
    return 0


def _tsv(path: str) -> list[dict[str, str]]:
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))


def _first_line(path: str) -> str:
    """The first output line of a probe file (line 1 is the recorded command)."""
    if not os.path.exists(path):
        return "(missing)"
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().splitlines()
    body = [ln for ln in lines[1:] if not ln.startswith("rc=")]
    return body[0].strip().replace("|", "\\|") if body else "(no output)"


def _rc(path: str) -> str:
    if not os.path.exists(path):
        return "missing"
    with open(path, encoding="utf-8", errors="replace") as fh:
        for ln in reversed(fh.read().splitlines()):
            if ln.startswith("rc="):
                return ln[3:]
    return "?"


def _worked(rows: list[dict[str, str]], component: str, os_only: bool = False) -> str:
    for r in rows:
        if r["component"] == component and r["imports"] == "yes":
            if os_only and r["kind"] == "pip":
                continue
            return f"`{r['line']}` ({r['kind']})"
    tried = sum(1 for r in rows if r["component"] == component and not (os_only and r["kind"] == "pip"))
    return f"none worked ({tried} tried)"


def summarize(root: str) -> int:
    lines = ["# Guest host facts", "",
             "Generated by tests/guest-facts/runner_side.py from the fixtures beside it.", "",
             "| Guest | uname -s / -r | CPU (uname -p; isainfo -k) | image sha256 | Python | urwid | PySide6 | PyQt6 "
             "| stock --self-check rc | installed --self-check rc | plain-TUI session |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    green_sets = []
    sizing_lines = []
    dragonfly = "DragonFly: no fixtures."
    for guest in GUESTS:
        d = os.path.join(root, guest)
        if not os.path.isdir(d):
            lines.append(f"| {guest} | (missing) | | | | | | | | | |")
            continue
        inst = _tsv(os.path.join(d, "install.tsv"))
        img = [r for r in _tsv(os.path.join(d, "image.tsv")) if r["kind"] == "image"]
        digest = ", ".join(f"`{r['sha256']}` ({r['path']})" for r in img) or "(not recorded)"
        steps = {r["step"]: r["rc"] for r in _tsv(os.path.join(d, "session", "steps.tsv"))}
        session = (f"tui rc {steps.get('tui', 'missing')}, print rc {steps.get('print', 'missing')}"
                   if steps else "(not run)")
        cpu = f"{_first_line(os.path.join(d, 'uname-p.txt'))}; {_first_line(os.path.join(d, 'isainfo-k.txt'))}"
        lines.append(
            f"| {guest} | {_first_line(os.path.join(d, 'uname-s.txt'))} {_first_line(os.path.join(d, 'uname-r.txt'))} "
            f"| {cpu} | {digest} | {_worked(inst, 'python')} | {_worked(inst, 'urwid')} "
            f"| {_worked(inst, 'pyside6')} | {_worked(inst, 'pyqt6')} "
            f"| {_rc(os.path.join(d, 'selfcheck-stock.txt'))} | {_rc(os.path.join(d, 'selfcheck-installed.txt'))} "
            f"| {session} |")
        sizing = _tsv(os.path.join(d, "contract-sizing.tsv"))
        if sizing:
            counts: dict[str, int] = {}
            for r in sizing:
                counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
            sizing_lines.append(f"- {guest}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
            if "not-run" not in counts:
                green_sets.append({r["file"] for r in sizing if r["verdict"] == "green"})
        else:
            sizing_lines.append(f"- {guest}: no sizing run")
        if guest == "dragonfly":
            urwid_os = _worked(inst, "urwid", os_only=True)
            pyqt = _worked(inst, "pyqt6", os_only=True)
            dragonfly = (f"DragonFly {_first_line(os.path.join(d, 'uname-r.txt'))} (the release the VM action booted): "
                         f"urwid from the OS packages: {'FOUND ' + urwid_os if 'none worked' not in urwid_os else 'NOT FOUND (' + urwid_os + ')'}; "
                         f"PyQt6 from the OS packages: {'FOUND ' + pyqt if 'none worked' not in pyqt else 'NOT FOUND (' + pyqt + ')'}.")
    contract = sorted(set.intersection(*green_sets)) if green_sets else []
    lines += ["", dragonfly, "", "## Contract sizing (named-file text-UI and CLI list)", ""] + sizing_lines
    lines += ["", f"{len(contract)} files were green on every guest whose sizing run finished "
                  f"({len(green_sets)} of {len(GUESTS)}); they are listed in contract-list.txt.", ""]
    with open(os.path.join(root, "SUMMARY.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    with open(os.path.join(root, "contract-list.txt"), "w", encoding="utf-8") as fh:
        fh.write("".join(f"{f}\n" for f in contract))
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="mode", required=True)
    i = sub.add_parser("image")
    i.add_argument("--out", required=True)
    i.add_argument("--action", required=True)
    i.add_argument("--release", required=True)
    i.add_argument("--data-dir", required=True)
    i.add_argument("--actions-dir", required=True)
    s = sub.add_parser("summarize")
    s.add_argument("--root", required=True)
    args = ap.parse_args(argv)
    if args.mode == "image":
        return image(args.out, args.action, args.release, args.data_dir, args.actions_dir)
    return summarize(args.root)


if __name__ == "__main__":
    raise SystemExit(main())
