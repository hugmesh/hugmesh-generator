"""Codec conformance tests — stdlib only (run: python3 -m unittest discover tests/meshbridge).

The wire vectors were generated by gen_vectors.py against the OFFICIAL
Meshtastic protobuf bindings (see its header); these tests pin the bridge's
hand-written codec to them, plus exercise the stream framing's resync
behaviour, which the vectors can't capture.
"""

import json
import pathlib
import sys
import unittest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "specs/cluster/manifests/meshbridge/app"))

import meshtastic_codec as codec  # noqa: E402


def revive(v):
    if isinstance(v, dict):
        if set(v) == {"__bytes__"}:
            return bytes.fromhex(v["__bytes__"])
        return {k: revive(x) for k, x in v.items()}
    return v


VECTORS = json.loads((HERE / "vectors" / "wire_vectors.json").read_text())
PARSERS = {"FromRadio": codec.parse_from_radio, "Telemetry": codec.parse_telemetry}


class DecodeVectors(unittest.TestCase):
    def test_all_decode_vectors(self):
        for case in VECTORS["decode"]:
            with self.subTest(case["name"]):
                got = PARSERS[case["parser"]](bytes.fromhex(case["hex"]))
                self.assertEqual(got, revive(case["expect"]))


class EncodeVectors(unittest.TestCase):
    """The committed bytes were verified radio-compatible at generation time;
    re-building them must be byte-identical (encode regression pin)."""

    def _rebuild(self, name: str) -> bytes:
        if name == "text_broadcast_ch1":
            return codec.build_text_packet(1, "[alice] hi mesh".encode(), 0x0000C0DE)
        if name == "text_ch0_no_ack":
            return codec.build_text_packet(0, "0-ch default".encode(), 1,
                                           want_ack=False, hop_limit=7)
        if name == "want_config":
            return codec.build_want_config(0xBEEF)
        if name == "heartbeat":
            return codec.build_heartbeat()
        raise AssertionError(f"unknown encode vector {name}")

    def test_all_encode_vectors(self):
        for case in VECTORS["encode"]:
            with self.subTest(case["name"]):
                self.assertEqual(self._rebuild(case["name"]).hex(), case["hex"])

    def test_encoded_frames_decode_back(self):
        for case in VECTORS["encode"]:
            with self.subTest(case["name"]):
                self.assertIsInstance(
                    codec.parse_to_radio(bytes.fromhex(case["hex"])), dict)


class Builders(unittest.TestCase):
    def test_payload_cap_enforced(self):
        codec.build_text_packet(0, b"x" * codec.DATA_PAYLOAD_LEN, 1)
        with self.assertRaises(ValueError):
            codec.build_text_packet(0, b"x" * (codec.DATA_PAYLOAD_LEN + 1), 1)

    def test_node_id_helpers(self):
        self.assertEqual(codec.node_id_from_num(0xDEADBEEF), "!deadbeef")
        self.assertEqual(codec.num_from_node_id("!deadbeef"), 0xDEADBEEF)
        self.assertEqual(codec.num_from_node_id("DEADBEEF"), 0xDEADBEEF)
        self.assertIsNone(codec.num_from_node_id("!deadbee"))
        self.assertIsNone(codec.num_from_node_id("!deadbeefe"))
        self.assertIsNone(codec.num_from_node_id("nothexy!"))

    def test_packet_id_masked_to_32_bits(self):
        wire = codec.build_text_packet(0, b"hi", 0x1_0000_0001)
        self.assertEqual(codec.parse_to_radio(wire)["packet"]["id"], 1)


class Decoder(unittest.TestCase):
    def test_truncated_varint_raises(self):
        with self.assertRaises(codec.DecodeError):
            codec.parse_from_radio(b"\x80")

    def test_truncated_length_delimited_raises(self):
        # field 2 (packet), LEN, claims 10 bytes but provides 1
        with self.assertRaises(codec.DecodeError):
            codec.parse_from_radio(b"\x12\x0a\x00")

    def test_group_wire_type_raises(self):
        with self.assertRaises(codec.DecodeError):
            codec.parse_from_radio(b"\x0b")  # field 1, wire type 3 (SGROUP)

    def test_empty_payload_is_empty_dict(self):
        self.assertEqual(codec.parse_from_radio(b""), {})

    def test_wire_type_mismatch_is_skipped_not_fatal(self):
        # FromRadio field 7 (config_complete_id) sent as LEN instead of varint:
        # a dialect mismatch skips the field but keeps the rest of the message.
        buf = b"\x3a\x02\xff\xff" + b"\x40\x01"  # field7 LEN + field8 rebooted=1
        self.assertEqual(codec.parse_from_radio(buf), {"rebooted": True})


class Framing(unittest.TestCase):
    def test_roundtrip(self):
        payload = codec.build_heartbeat()
        parser = codec.StreamParser()
        self.assertEqual(parser.feed(codec.frame(payload)), [payload])

    def test_split_delivery_across_feeds(self):
        payload = codec.build_want_config(7)
        wire = codec.frame(payload)
        parser = codec.StreamParser()
        got = []
        for i in range(len(wire)):
            got += parser.feed(wire[i:i + 1])
        self.assertEqual(got, [payload])

    def test_garbage_between_frames_resyncs(self):
        p1, p2 = codec.build_heartbeat(), codec.build_want_config(3)
        wire = b"radio boot log\r\n" + codec.frame(p1) + b"\x94 stray" + codec.frame(p2)
        parser = codec.StreamParser()
        self.assertEqual(parser.feed(wire), [p1, p2])
        self.assertGreater(parser.garbage_bytes, 0)

    def test_oversize_length_resyncs_instead_of_erroring(self):
        p = codec.build_heartbeat()
        bad = bytes((codec.START1, codec.START2, 0xFF, 0xFF))
        parser = codec.StreamParser()
        self.assertEqual(parser.feed(bad + codec.frame(p)), [p])

    def test_lone_start_byte_held_for_next_feed(self):
        p = codec.build_heartbeat()
        wire = codec.frame(p)
        parser = codec.StreamParser()
        self.assertEqual(parser.feed(wire[:1]), [])
        self.assertEqual(parser.feed(wire[1:]), [p])

    def test_back_to_back_frames_one_feed(self):
        p1, p2, p3 = (codec.build_want_config(n) for n in (1, 2, 3))
        parser = codec.StreamParser()
        self.assertEqual(
            parser.feed(codec.frame(p1) + codec.frame(p2) + codec.frame(p3)),
            [p1, p2, p3])

    def test_frame_rejects_oversize_payload(self):
        with self.assertRaises(ValueError):
            codec.frame(b"x" * (codec.MAX_FRAME_PAYLOAD + 1))


if __name__ == "__main__":
    unittest.main()
